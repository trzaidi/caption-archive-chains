import Link from 'next/link';
import { notFound } from 'next/navigation';
import { Shell } from '@/components/shell';
import { DeleteRunButton } from '@/components/delete-run';
import { RUN_SELECT, signRuns, type RunWithSteps } from '@/components/media-grid';
import { requireAdmin } from '@/lib/admin';
import { duration, when } from '@/lib/format';

export const dynamic = 'force-dynamic';

export default async function RunPage({ params }: { params: Promise<{ id: string }> }) {
  const { supabase, user } = await requireAdmin();
  const id = Number((await params).id);
  if (!Number.isSafeInteger(id) || id < 1) notFound();
  const { data: run } = await supabase.from('prompt_chain_runs').select(RUN_SELECT).eq('id', id).maybeSingle<RunWithSteps>();
  if (!run) notFound();
  const urls = await signRuns(supabase, [run]);
  const steps = [...run.prompt_chain_run_steps].sort((a, b) => a.step_order - b.step_order);
  const total = steps.reduce((t, s) => t + (s.duration_ms ?? 0), 0);
  const tokens = steps.reduce((t, s) => t + (s.input_tokens ?? 0) + (s.output_tokens ?? 0), 0);
  const { data: chainExists } = await supabase.from('prompt_chains').select('id').eq('id', run.prompt_chain_id).maybeSingle();

  return (
    <Shell active="/media" email={user.email ?? ''}>
      <nav className="crumbs" aria-label="Breadcrumb">
        <Link href="/">Chains</Link><span>/</span>
        {chainExists ? <Link href={`/chains/${run.prompt_chain_id}`}>{run.chain_name}</Link> : <span>{run.chain_name}</span>}<span>/</span>
        {chainExists && <><Link href={`/chains/${run.prompt_chain_id}/media`}>Media</Link><span>/</span></>}
        <span>Run #{run.id}</span>
      </nav>
      <div className="pagehead">
        <div>
          <h1>Run #{run.id}</h1>
          <div className="kv">
            <span className={`badge ${run.status === 'succeeded' ? 'ok' : run.status === 'failed' ? 'fail' : 'run'}`}>{run.status}</span>
            <span>{when(run.created_at)}</span><span>{steps.length} steps</span><span>{duration(total)} model time</span>{tokens > 0 && <span>{tokens.toLocaleString()} tokens</span>}
          </div>
        </div>
        <div className="row">
          {chainExists && <Link className="btn" href={`/chains/${run.prompt_chain_id}`}>Open chain</Link>}
          <DeleteRunButton id={run.id} />
        </div>
      </div>
      {run.error && <p className="notice error" style={{ marginBottom: 18 }}>{run.error}</p>}
      <ol className="trace">
        <li className="card">
          <h2>Input</h2>
          {run.input_image_path && urls.get(run.input_image_path) && <img className="inputimg" src={urls.get(run.input_image_path)} alt="Run input" />}
          {run.input_text ? <p className="output" style={{ marginTop: 12 }}>{run.input_text}</p> : !run.input_image_path && <p className="muted">No input.</p>}
        </li>
        {steps.map((s) => (
          <li key={s.id} className="card">
            <div className="cardhead">
              <h2>{s.step_order}. {s.title}</h2>
              <span className={`badge ${s.status === 'succeeded' ? 'ok' : s.status === 'skipped' ? '' : 'fail'}`}>{s.status}</span>
            </div>
            <div className="kv" style={{ marginBottom: 12 }}>
              <span className="mono">{s.model ?? 'No model call'}</span><span>{duration(s.duration_ms)}</span>
              {s.input_tokens != null && <span>{s.input_tokens} in / {s.output_tokens ?? 0} out tokens</span>}
            </div>
            {s.output_text && <div className="output">{s.output_text}</div>}
            {s.output_image_path && urls.get(s.output_image_path) && <img src={urls.get(s.output_image_path)} alt={`Generated by step ${s.step_order}`} />}
            {s.error && <p className="notice error">{s.error}</p>}
            {s.status === 'skipped' && <p className="muted small">No model call. The previous output passed through unchanged.</p>}
            <details style={{ marginTop: 12 }}>
              <summary className="muted small" style={{ cursor: 'pointer' }}>Exact prompt sent</summary>
              <pre style={{ marginTop: 8 }}>{s.prompt_sent}</pre>
            </details>
          </li>
        ))}
      </ol>
    </Shell>
  );
}
